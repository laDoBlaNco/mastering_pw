/**
 * Relational or comparison operators return boolean
 * 
 * > - greater than
 * < - less than
 * >= - greater than or equal to
 * <= - less than or equal to
 * 
 */

let result = 10 > 5
let result2 = 4 > 5
console.log(result)
console.log(result2)

let result3 = 5 >= 5
console.log(result3)

let x = 1
console.log(x == '1') // loose comparion, value but not data type (number vs string)
console.log(x === '1') // strict comparison, value and type (number vs string)
console.log(x === 1)



